# Usage: python3 -I gen_fw.py <hal8821a_fw.c> <out.c>
# Extracts array_mp_8821a_fw_nic into a C source (const uint8_t fw8821a[] + fw8821a_len).
import re, sys
src = open(sys.argv[1], 'rb').read().decode('latin-1')
m = re.search(r"u8 array_mp_8821a_fw_nic\[\]\s*=\s*\{(.*?)\};", src, re.S)
vals = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(1))]
n = int(re.search(r"array_length_mp_8821a_fw_nic\s*=\s*(\d+)", src).group(1))
assert len(vals) == n, (len(vals), n)
o = ["// Generated by tools/gen_fw.py from hal8821a_fw.c (array_mp_8821a_fw_nic). Do not edit.",
     "#include <stdint.h>", "#include <stddef.h>", "const uint8_t fw8821a[] = {"]
for i in range(0, n, 16):
    o.append("    " + ", ".join("0x%02X" % v for v in vals[i:i+16]) + ",")
o += ["};", "const size_t fw8821a_len = %d;" % n]
open(sys.argv[2], 'w').write("\n".join(o) + "\n")
print("fw bytes:", n)
