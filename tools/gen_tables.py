#!/usr/bin/env python3
# Generate src/tables.c and src/tables.h from the Linux rtl8812au PHYDM headers (read as data only).
# Usage: python3 -I tools/gen_tables.py REF_DIR OUT_DIR
#   REF_DIR = ref-rtl8812au (root of the aircrack-ng driver), OUT_DIR = src
import re, sys, os

ref, out = sys.argv[1], sys.argv[2]
base = os.path.join(ref, "hal/phydm/rtl8821a")
# (C name in output, source file, source array name, words per entry)
TABLES = [
    ("mac",   "halhwimg8821a_mac.c", "array_mp_8821a_mac_reg", 2),
    ("bb",    "halhwimg8821a_bb.c",  "array_mp_8821a_phy_reg", 2),
    ("agc",   "halhwimg8821a_bb.c",  "array_mp_8821a_agc_tab", 2),
    ("rf_a",  "halhwimg8821a_rf.c",  "array_mp_8821a_radioa",  2),
    ("bb_pg", "halhwimg8821a_bb.c",  "array_mp_8821a_phy_reg_pg", 6),
]

def parse(path, name):
    src = open(path, encoding="utf-8", errors="replace").read()
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    m = re.search(r"\b" + re.escape(name) + r"\s*\[\s*\]\s*=\s*\{(.*?)\}\s*;", src, flags=re.S)
    if not m:
        sys.exit("array %s not found in %s" % (name, path))
    return [int(t, 0) for t in re.findall(r"0[xX][0-9a-fA-F]+|\b\d+\b", m.group(1))]

c = ["// GENERATED by tools/gen_tables.py from the Linux rtl8812au PHYDM RTL8821A tables. Do not edit.",
     "// Entries with bit31/bit30 set in the first word are if/else-if/else/endif markers (see phy.c).",
     '#include "tables.h"', ""]
h = ["// GENERATED by tools/gen_tables.py. Do not edit.", "#ifndef TABLES_H", "#define TABLES_H",
     "#include <stdint.h>", "#include <stddef.h>", ""]
for cname, f, aname, w in TABLES:
    vals = parse(os.path.join(base, f), aname)
    if len(vals) % w:
        sys.exit("%s: %d words not a multiple of %d" % (aname, len(vals), w))
    c.append("// source: %s (%s), %d entries" % (aname, f, len(vals) // w))
    c.append("const uint32_t rtl_tab_%s[] = {" % cname)
    for i in range(0, len(vals), w):
        c.append("\t" + ", ".join("0x%08X" % v for v in vals[i:i + w]) + ",")
    c.append("};")
    c.append("const size_t rtl_tab_%s_len = sizeof(rtl_tab_%s) / sizeof(uint32_t);" % (cname, cname))
    c.append("")
    h.append("extern const uint32_t rtl_tab_%s[];  // %d words per entry" % (cname, w))
    h.append("extern const size_t rtl_tab_%s_len;  // in words" % cname)
h += ["", "#endif", ""]
open(os.path.join(out, "tables.c"), "w").write("\n".join(c))
open(os.path.join(out, "tables.h"), "w").write("\n".join(h))
print("wrote tables.c/tables.h")
