# Usage: python3 -I gen_pwrseq.py <Hal8821APwrSeq.h> <out.h>
# Extracts the CARDDIS_TO_CARDEMU and CARDEMU_TO_ACT tables (data only; reference code is never run).
import re, sys
src = open(sys.argv[1], 'rb').read().decode('latin-1')
out = ["// Generated by tools/gen_pwrseq.py from Hal8821APwrSeq.h. Do not edit.",
       "// { offset, cut_msk, fab_msk, intf_msk, cmd, msk, value }"]
for name in ("CARDDIS_TO_CARDEMU", "CARDEMU_TO_ACT"):
    m = re.search(r"#define RTL8821A_TRANS_%s\s.*?(?=\n#define|\Z)" % name, src, re.S)
    out.append("static const struct pwr_cmd pwr_%s[] = {" % name.lower())
    for e in re.finditer(r"^\s*\{\s*(0x[0-9A-Fa-f]+),\s*([^,]+),\s*([^,]+),\s*([^,]+?),\s*PWR_BASEADDR_\w+,\s*(PWR_CMD_\w+),\s*(.+?)\s*,\s*([^,]+?)\s*\}\s*,", m.group(0), re.M):
        out.append("    {%s, %s, %s, %s, %s, %s, %s}," % tuple(g.strip() for g in e.groups()))
    out.append("};")
open(sys.argv[2], 'w').write("\n".join(out) + "\n")
